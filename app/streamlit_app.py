"""
Front door for creating a dbt platform project with Terraform.

    pip install -r app/requirements.txt
    streamlit run app/streamlit_app.py

The form produces a terraform.tfvars file for modules/dbt_project. When the
Terraform CLI is on PATH (running locally) the app can also create
projects/<name>/ and run init / plan / apply there, so state lives with the
project directory (or its configured backend), not with the browser session.
Where there is no Terraform CLI (for example Streamlit in Snowflake) the app
only produces the file.
"""

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import streamlit as st

REPO_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_DIR / "scripts"))
from check_connection import read_variable_default, run_checks  # noqa: E402

PROJECTS_DIR = REPO_DIR / "projects"
TEMPLATE_DIR = PROJECTS_DIR / "example"
TEMPLATE_FILES = ["main.tf", "variables.tf", "outputs.tf", "providers.tf", "versions.tf", ".terraform.lock.hcl"]


def hcl(value, indent=0):
    """Render a Python value as HCL. Strings use JSON escaping, which HCL accepts."""
    pad = "  " * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, dict):
        width = max(len(k) for k in value)
        rows = [f"{pad}  {k.ljust(width)} = {hcl(v, indent + 1)}" for k, v in value.items()]
        return "{\n" + "\n".join(rows) + f"\n{pad}}}"
    return json.dumps(str(value))


def build_tfvars(values):
    """terraform.tfvars content from a dict, skipping None and empty values."""
    kept = {k: v for k, v in values.items() if v not in (None, "", {})}
    width = max(len(k) for k in kept)
    lines = ["# Generated by app/streamlit_app.py. Contains no secrets."]
    lines += [f"{k.ljust(width)} = {hcl(v)}" for k, v in kept.items()]
    return "\n".join(lines) + "\n"


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def prepare_project_dir(slug, tfvars):
    """Create projects/<slug>/ from the example project and write its tfvars."""
    target = PROJECTS_DIR / slug
    target.mkdir(parents=True, exist_ok=True)
    for name in TEMPLATE_FILES:
        if (TEMPLATE_DIR / name).exists() and not (target / name).exists():
            shutil.copy2(TEMPLATE_DIR / name, target / name)
    (target / "terraform.tfvars").write_text(tfvars, encoding="utf-8")
    return target


def run_terraform(workdir, secrets, *args):
    env = os.environ.copy()
    env.update({k: v for k, v in secrets.items() if v})
    env["TF_IN_AUTOMATION"] = "1"
    try:
        result = subprocess.run(
            ["terraform", *args, "-no-color"],
            cwd=workdir, env=env, capture_output=True, text=True, timeout=600,
        )
    except subprocess.TimeoutExpired:
        return False, "Terraform timed out after 10 minutes."
    return result.returncode == 0, (result.stdout + "\n" + result.stderr).strip()


def form():
    st.subheader("Account")
    col1, col2 = st.columns(2)
    account_id = col1.number_input("dbt account ID", min_value=1, value=None, step=1, format="%d")
    host_url = col2.text_input("API URL", value="https://cloud.getdbt.com/api", help="Ends in /api")

    st.subheader("Project")
    project_name = st.text_input("Project name", placeholder="BHP_SANDBOX", help="Upper case with underscores.")
    project_description = st.text_input("Description", value="Created by Terraform")
    default_connection = read_variable_default(
        (TEMPLATE_DIR / "variables.tf").read_text(encoding="utf-8"), "connection_id"
    )
    connection_id = st.number_input(
        "Connection ID (optional)", min_value=1, value=None, step=1, format="%d",
        help=f"Leave empty to use the shared Snowflake connection ({default_connection}). "
        "Connections are shared, not created per project.",
    )
    create_groups = st.checkbox(
        "Create <PROJECT_NAME>_ADMIN and <PROJECT_NAME>_DEVS groups", value=True,
        help="Admin and Developer on this project, with write access to all environments.",
    )

    st.subheader("Environments")
    col1, col2 = st.columns(2)
    dbt_version = col1.selectbox(
        "dbt version", ["fusion-stable", "latest-fusion", "latest", "compatible", "extended"]
    )
    enable_dbt_state = col2.checkbox("Enable dbt State", value=False)
    use_staging = st.checkbox(
        "Add a staging branch", value=False,
        help="Off: Development, Production, Production CI. On: also Staging and Staging CI.",
    )
    staging_branch = st.text_input("Staging branch", value="staging") if use_staging else None

    st.subheader("Deployment credentials")
    create_credentials = st.checkbox(
        "Create Snowflake key-pair credentials", value=False,
        help="Off: environments are created without credentials; finish them in the dbt platform.",
    )
    snowflake_deployment = None
    if create_credentials:
        col1, col2 = st.columns(2)
        snowflake_deployment = {
            "user": col1.text_input("Service user"),
            "database": col2.text_input("Database"),
            "role": col1.text_input("Role"),
            "warehouse": col2.text_input("Warehouse"),
        }
        snowflake_deployment = {k: v for k, v in snowflake_deployment.items() if v}

    st.subheader("Jobs")
    job_options = {
        "bootstrap": "Create once, then leave to the team (changes in the UI are kept)",
        "managed": "Managed by Terraform (changes in the UI are reverted)",
        "none": "No starter jobs",
    }
    job_management = st.radio(
        "Starter jobs (Build, Merge, CI)", list(job_options), format_func=job_options.get
    )
    job_triggers = {}
    if job_management != "none":
        st.caption("Leave triggers off until a repository is attached and the Build job has run once.")
        col1, col2, col3 = st.columns(3)
        job_triggers = {
            "schedule": col1.checkbox("Schedule", value=False),
            "ci": col2.checkbox("CI on pull request", value=False),
            "merge": col3.checkbox("On merge", value=False),
        }
        job_triggers = job_triggers if any(job_triggers.values()) else {}

    missing = [
        label for label, value in
        [("dbt account ID", account_id), ("Project name", project_name.strip())]
        if not value
    ]
    if create_credentials and not {"user", "database"} <= set(snowflake_deployment):
        missing.append("Service user and Database")

    values = {
        "dbt_account_id": int(account_id) if account_id else None,
        "dbt_host_url": host_url.strip(),
        "project_name": project_name.strip(),
        "project_description": project_description.strip(),
        "connection_id": int(connection_id) if connection_id else None,
        "dbt_version": dbt_version,
        "enable_dbt_state": True if enable_dbt_state else None,
        "staging_branch": staging_branch,
        "snowflake_deployment": snowflake_deployment,
        "create_groups": None if create_groups else False,
        "job_management": None if job_management == "bootstrap" else job_management,
        "job_triggers": job_triggers,
    }
    connection_to_check = values["connection_id"] or default_connection
    return values, missing, create_credentials, connection_to_check


def local_runner(values, tfvars, needs_key, connection_to_check):
    st.subheader("Run Terraform on this machine")
    slug = st.text_input(
        "Project directory", value=slugify(values["project_name"]),
        help="Created under projects/. One directory, and one state, per dbt project.",
    )
    token = st.text_input("DBT_CLOUD_TOKEN", type="password", help="Used for this run only. Never written to disk.")
    private_key = ""
    if needs_key:
        private_key = st.text_area("Snowflake private key (PEM)", help="Used for this run only. Never written to disk or state.")
    secrets = {"DBT_CLOUD_TOKEN": token, "TF_VAR_snowflake_private_key": private_key}

    if not slug or slug == "example":
        st.info("Choose a project directory name other than 'example'.")
        return
    if not token:
        st.info("Enter a dbt platform API token to run Terraform.")
        return

    if st.button("Test connection"):
        results = run_checks(token, values["dbt_account_id"], values["dbt_host_url"], connection_to_check)
        for name, passed, detail in results:
            (st.success if passed else st.error)(f"{name}: {detail}")

    confirm = st.checkbox(f"I have reviewed the plan for projects/{slug}")
    confirm_destroy = st.checkbox(f"Allow destroy of everything in projects/{slug}")
    col1, col2, col3 = st.columns(3)
    action = None
    if col1.button("Plan"):
        action = ["plan", "-input=false"]
    if col2.button("Apply", disabled=not confirm, type="primary"):
        action = ["apply", "-input=false", "-auto-approve"]
    if col3.button("Destroy", disabled=not confirm_destroy):
        action = ["destroy", "-input=false", "-auto-approve"]

    if action:
        workdir = prepare_project_dir(slug, tfvars)
        with st.spinner(f"terraform {action[0]} in projects/{slug}"):
            ok, output = run_terraform(workdir, secrets, "init", "-input=false")
            if ok:
                ok, output = run_terraform(workdir, secrets, *action)
        st.code(output or "(no output)", language="text")
        (st.success if ok else st.error)(f"terraform {action[0]} {'finished' if ok else 'failed'}.")
    st.caption(
        "State is kept in the project directory (or its backend). On a host with no persistent disk "
        "and no backend, state lasts only as long as the container: fine for create and destroy in "
        "one sitting, not for managing a project over time."
    )


def main():
    st.set_page_config(page_title="dbt project factory")
    st.title("dbt project factory")
    st.caption("Creates a dbt platform project with standard environments and starter jobs, through Terraform.")

    values, missing, needs_key, connection_to_check = form()

    st.divider()
    if missing:
        st.warning("Still needed: " + ", ".join(missing))
        return

    tfvars = build_tfvars(values)
    st.subheader("terraform.tfvars")
    st.code(tfvars, language="hcl")
    st.download_button("Download terraform.tfvars", tfvars, file_name="terraform.tfvars")

    st.divider()
    if shutil.which("terraform"):
        local_runner(values, tfvars, needs_key, connection_to_check)
    else:
        st.info(
            "The Terraform CLI is not available here, so this app only produces the file. "
            "Commit it as projects/<name>/terraform.tfvars and let the pipeline plan and apply it."
        )


if __name__ == "__main__":
    main()
